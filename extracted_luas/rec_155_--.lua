--
-- 不在此文件内的中文（有意保留在原处）：
--   * 代码注释（文档说明，非玩家可见）
--   * 图片资源文件名（consignment_ui_updater.lua 的 IMG 表，对应实际素材文件，勿改）
--   * 调试日志 Info() 里的中文（开发排查用，非玩家可见）
-- ================================================================

